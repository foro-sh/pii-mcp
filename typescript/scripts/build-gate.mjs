/**
 * Bundle the Tier 1 gate entry into a single ESM file for container COPY.
 *
 * Output: ``gate/pii-gate.mjs`` — zero npm packages; only Node built-ins
 * (``node:net`` for IP validation). Sync and pattern-only; no native/NER.
 */
import * as esbuild from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = join(root, "gate", "pii-gate.mjs");

mkdirSync(dirname(outfile), { recursive: true });

await esbuild.build({
  absWorkingDir: root,
  entryPoints: ["src/gate.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  outfile,
  legalComments: "none",
  logLevel: "info",
});

const banner = [
  "/**",
  " * Generated by `npm run build:gate` — do not edit.",
  " * Tier 1 gate scrubber (sync, pattern-only, zero npm deps).",
  " * Source: typescript/src/gate.ts + scrub-js + detectors + types.",
  " * Contract: docs/tier1-gate.md",
  " */",
  "",
].join("\n");

const body = readFileSync(outfile, "utf8");
const disallowed = [...body.matchAll(/from\s+["']([^"']+)["']/g)]
  .map((m) => m[1])
  .filter((spec) => !spec.startsWith("node:"));
if (disallowed.length > 0) {
  throw new Error(
    `gate artifact has non-Node imports (must be zero npm deps): ${disallowed.join(", ")}`,
  );
}

writeFileSync(outfile, banner + body);
console.log(`wrote ${outfile}`);
